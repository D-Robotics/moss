/**
 * `moss init` — onboarding to the first verified result.
 *
 * Best products reduce first-run friction to "detect the project, write the
 * conventions file, show the next command". Moss already proposes acceptance
 * commands from real workspace files (`/goal` without `--accept`), so `init`
 * reuses that: it detects test/build/lint entry points, writes a minimal
 * `AGENTS.md` (only when absent — never overwrite instructions the user owns),
 * and prints the exact `moss run … --accept …` to try next. Read-only mode
 * (`--dry-run`) prints the file instead of writing it; no model config needed.
 */
import fs from 'node:fs';
import path from 'node:path';
import { proposeAcceptanceCommands } from './commands/goal-propose.js';
import { isZhLocale } from './cli-locale.js';

export interface InitDetection {
  kind: 'node' | 'python' | 'go' | 'make' | 'unknown';
  commands: { label: string; command: string }[];
  acceptanceCandidates: string[];
}

export interface InitResult {
  version: 1;
  workspace: string;
  agentsFile: string;
  exists: boolean;
  written: boolean;
  dryRun: boolean;
  detection: InitDetection;
  content: string;
}

function readPackageScripts(workspace: string): Record<string, string> {
  try {
    const parsed = JSON.parse(fs.readFileSync(path.join(workspace, 'package.json'), 'utf8')) as {
      scripts?: Record<string, unknown>;
    };
    const scripts: Record<string, string> = {};
    for (const [name, value] of Object.entries(parsed.scripts ?? {})) {
      if (typeof value === 'string' && value.trim() !== '') scripts[name] = value.trim();
    }
    return scripts;
  } catch {
    return {};
  }
}

function makefileHasTest(workspace: string): boolean {
  try {
    return /^test\s*:/m.test(fs.readFileSync(path.join(workspace, 'Makefile'), 'utf8'));
  } catch {
    return false;
  }
}

/** Detect the entry points an agent would actually need. Files, not guesses. */
export function detectProject(workspace: string): InitDetection {
  const commands: { label: string; command: string }[] = [];
  const scripts = readPackageScripts(workspace);
  let kind: InitDetection['kind'] = 'unknown';
  if (Object.keys(scripts).length > 0) {
    kind = 'node';
    for (const label of ['test', 'build', 'lint', 'typecheck', 'check']) {
      if (scripts[label]) {
        commands.push({
          label,
          command: label === 'test' ? 'npm test' : `npm run ${label}`,
        });
      }
    }
  }
  if (commands.length === 0 && makefileHasTest(workspace)) {
    kind = 'make';
    commands.push({ label: 'test', command: 'make test' });
  }
  const hasGo = fs.existsSync(path.join(workspace, 'go.mod'));
  if (commands.length === 0 && hasGo) {
    kind = 'go';
    commands.push({ label: 'test', command: 'go test ./...' });
  }
  const pyproject = fs.existsSync(path.join(workspace, 'pyproject.toml'));
  const requirements = fs.existsSync(path.join(workspace, 'requirements.txt'));
  if (commands.length === 0 && (pyproject || requirements)) {
    kind = 'python';
  }
  const acceptanceCandidates = proposeAcceptanceCommands(workspace).candidates;
  return { kind, commands, acceptanceCandidates };
}

function renderAgentsFile(detection: InitDetection, zh: boolean): string {
  const date = new Date().toISOString().slice(0, 10);
  const commandLines =
    detection.commands.length > 0
      ? detection.commands.map((entry) => `- ${entry.label}: \`${entry.command}\``)
      : [
          zh
            ? '- 没有找到 test/build/lint 入口；把你实际使用的命令写在这里。'
            : '- No test/build/lint entry points detected; add the commands this project uses.',
        ];
  const acceptance = detection.acceptanceCandidates[0];
  const acceptanceLines = acceptance
    ? [
        zh
          ? '自主运行（`moss run … --accept "<命令>"`）的验收命令：'
          : 'Acceptance command for autonomous runs (`moss run … --accept "<cmd>"`):',
        '',
        '```bash',
        acceptance,
        '```',
      ]
    : [
        zh
          ? '这个工作区没有可机检的验收入口。`moss run` 会退回任务契约裁决；如果你有验收脚本，把命令写在这里。'
          : 'No machine-checkable acceptance entry point was detected. `moss run` will fall back to the task-contract verdict; if you have a check script, put its command here.',
      ];
  return [
    `# AGENTS.md`,
    '',
    zh
      ? `<!-- 由 \`moss init\` 于 ${date} 生成；这是项目说明，可直接编辑。 -->`
      : `<!-- Generated by \`moss init\` on ${date}. This file is project instructions; edit it freely. -->`,
    '',
    '## Commands',
    '',
    ...commandLines,
    '',
    '## Verification',
    '',
    ...acceptanceLines,
    '',
    '## Notes',
    '',
    zh
      ? '- 提交前先跑上面的 test 命令；失败就是失败，不要跳过。'
      : '- Run the test command above before declaring work done; a red check is not done.',
    zh
      ? '- 破坏性操作（设备重启/刷机/改网络）要显式确认。'
      : '- Destructive operations (device reboot/flash/network changes) need explicit confirmation.',
    '',
  ].join('\n');
}

export function buildInitResult(
  workspace: string,
  options: { dryRun?: boolean; zh?: boolean } = {}
): InitResult {
  const zh = options.zh ?? isZhLocale();
  const detection = detectProject(workspace);
  const agentsFile = path.join(workspace, 'AGENTS.md');
  const exists = fs.existsSync(agentsFile);
  const content = renderAgentsFile(detection, zh);
  const dryRun = options.dryRun === true;
  const written = !exists && !dryRun;
  if (written) fs.writeFileSync(agentsFile, content, 'utf8');
  return {
    version: 1,
    workspace,
    agentsFile,
    exists,
    written,
    dryRun,
    detection,
    content,
  };
}

export function renderInitUsage(zh = isZhLocale()): string {
  return zh
    ? [
        '用法：',
        '  moss init [--dry-run] [--json]',
        '',
        '首次上手：检测工作区的 test/build/lint 入口与可用验收命令，',
        '写一份最小 AGENTS.md（已存在则绝不覆盖），并打印下一条该跑的命令。',
        '不需要模型配置；--dry-run 只打印将要写入的内容。',
        '',
        '示例：',
        '  moss init --dry-run',
        '  moss init',
      ].join('\n')
    : [
        'Usage:',
        '  moss init [--dry-run] [--json]',
        '',
        'First-run onboarding: detect test/build/lint entry points and a usable',
        'acceptance command, write a minimal AGENTS.md (never overwriting an existing',
        'one) and print the exact next command. No model configuration needed;',
        '--dry-run prints the file instead of writing it.',
        '',
        'Examples:',
        '  moss init --dry-run',
        '  moss init',
      ].join('\n');
}

export function renderInitHuman(result: InitResult, zh = isZhLocale()): string {
  const t = (en: string, cn: string): string => (zh ? cn : en);
  const lines = [
    t(`workspace: ${result.workspace}`, `工作区：${result.workspace}`),
    result.detection.commands.length > 0
      ? `${t('detected', '检测到')}: ${result.detection.commands
          .map((entry) => `${entry.label}=\`${entry.command}\``)
          .join(' · ')}`
      : t('detected: no test/build/lint entry points', '检测到：没有 test/build/lint 入口'),
  ];
  const acceptance = result.detection.acceptanceCandidates[0];
  lines.push(
    acceptance
      ? `${t('acceptance', '验收命令')}: \`${acceptance}\``
      : t(
          'acceptance: none detected (contract verdict will apply)',
          '验收命令：未检测到（将使用契约裁决）'
        )
  );
  if (result.exists) {
    lines.push(
      t(
        `AGENTS.md already exists at ${result.agentsFile} — left untouched.`,
        `AGENTS.md 已存在（${result.agentsFile}）——未改动。`
      )
    );
  } else if (result.dryRun) {
    lines.push(
      t('--dry-run: nothing written. Would create:', '--dry-run：未写入。将创建：'),
      '',
      result.content
    );
  } else if (result.written) {
    lines.push(t(`wrote ${result.agentsFile}`, `已写入 ${result.agentsFile}`), '', result.content);
  }
  lines.push('', t('next:', '下一步：'));
  if (acceptance) {
    lines.push(`  moss run "<intent>" --accept "${acceptance}"`);
  } else {
    lines.push('  moss run "<intent>"');
  }
  lines.push(
    '  moss capabilities        # ' + t('what this install can do', '一屏看清这个安装能做什么')
  );
  return lines.join('\n');
}

export interface InitCommandContext {
  workspace: string;
  outputJson?: boolean;
  output?: (stream: 'stdout' | 'stderr', text: string) => void;
}

export async function runInitCommand(
  args: readonly string[],
  ctx: InitCommandContext
): Promise<number> {
  const output =
    ctx.output ?? ((stream: 'stdout' | 'stderr', text: string) => process[stream].write(text));
  const zh = isZhLocale();
  let json = ctx.outputJson === true;
  let dryRun = false;
  for (const arg of args) {
    if (arg === '--json') json = true;
    else if (arg === '--dry-run') dryRun = true;
    else if (arg === '--help' || arg === '-h') {
      output('stdout', `${renderInitUsage(zh)}\n`);
      return 0;
    } else {
      output('stderr', `unknown argument ${arg}\n\n${renderInitUsage(zh)}\n`);
      return 2;
    }
  }
  const result = buildInitResult(ctx.workspace, { dryRun, zh });
  if (json) output('stdout', `${JSON.stringify(result, null, 2)}\n`);
  else output('stdout', `${renderInitHuman(result, zh)}\n`);
  return 0;
}
