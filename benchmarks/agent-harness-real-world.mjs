export const cases = Object.entries(scenarios).flatMap(([category, prompts]) => {
  const defaults = categoryDefaults[category];
  return prompts.map((prompt, index) => ({
    id: `${category}-${String(index + 1).padStart(2, '0')}`,
    category,
    priority: defaults.priority,
    mode: defaults.mode,
    sourceProjects: defaults.sourceProjects,
    sourceUrls: defaults.sourceProjects.map((project) => sources[project]),
    prompt,
    expectedSignals: categorySignals[category],
    forbiddenSignals: forbiddenSignals[category] ?? forbiddenSignals.default,
    status: 'not-run',
  }));
});

