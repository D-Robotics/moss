#!/usr/bin/env node
/**
 * `moss runs export` probe (offline, split from runs-ledger for CI budget).
 *
 * One run for a PR: `## Run …` Markdown / JSON / `--out`. Many runs for a week or
 * a CI day: `--since`/`--kind`/`--limit` produce one combined report (B182).
 */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { captureProcess } from './lib/proc.mjs';

const root = path.resolve(import.meta.dirname, '../..');
const load = (relative) => import(pathToFileURL(path.join(root, relative)).href);
const { writeRunRecord } = await load('dist/core/run-ledger.js');

let checks = 0;
const ok = (name) => {
  checks += 1;
  console.log(`[runs-export] ok ${name}`);
};

const tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'moss-runs-export-'));
const ws = path.join(tmp, 'ws');
await fs.mkdir(path.join(ws, '.moss'), { recursive: true });
const home = path.join(tmp, 'home');
const configDir = path.join(home, 'config');
await fs.mkdir(configDir, { recursive: true });
await fs.writeFile(
  path.join(configDir, 'config.json'),
  JSON.stringify({ provider: 'openai-compatible', model: 'm', baseUrl: 'http://127.0.0.1:9/v1' }),
  'utf8'
);
const env = {
  ...process.env,
  HOME: home,
  MOSS_CONFIG_DIR: configDir,
  MOSS_NO_RDK_DOCS: '1',
  MOSS_NO_TUI: '1',
  MOSS_LANG: 'en',
};
const cli = (args) =>
  captureProcess(process.execPath, [path.join(root, 'dist', 'cli.js'), ...args], {
    cwd: ws,
    env,
    timeoutMs: 60_000,
  });

const now = Date.now();
await writeRunRecord(ws, {
  version: 1,
  runId: 'task_paused',
  kind: 'task',
  status: 'interrupted',
  exitCode: 130,
  startedAt: now - 10_000,
  endedAt: now - 5_000,
  durationMs: 5_000,
  goal: 'paused run',
  taskId: 'task_paused',
  artifacts: { taskEvents: '.moss/task-events.jsonl' },
});
await writeRunRecord(ws, {
  version: 1,
  runId: 'task_fail',
  kind: 'task',
  status: 'verify_failed',
  exitCode: 1,
  startedAt: now - 30_000,
  endedAt: now - 20_000,
  durationMs: 10_000,
  goal: 'failed run',
  taskId: 'task_fail',
  reason: 'acceptance command failed (exit 1)',
  next: 'moss task resume task_fail',
  artifacts: { taskEvents: '.moss/task-events.jsonl' },
});
await writeRunRecord(ws, {
  version: 1,
  runId: 'task_ok',
  kind: 'task',
  status: 'completed',
  exitCode: 0,
  startedAt: now - 600,
  endedAt: now - 500,
  durationMs: 100,
  goal: 'passed run',
  taskId: 'task_ok',
  model: 'deepseek-flash@latest',
  usage: { inputTokens: 1_200, outputTokens: 84 },
  artifacts: {},
});
await writeRunRecord(ws, {
  version: 1,
  runId: 'loop_ok',
  kind: 'loop',
  status: 'completed',
  exitCode: 0,
  startedAt: now - 4_000,
  endedAt: now - 1_000,
  durationMs: 3_000,
  goal: 'loop run',
  artifacts: { loopLedger: '.moss/loops/loop_ok.jsonl' },
});

// 1. Single-run export: Markdown, JSON, --out, and usage errors.
const exported = await cli(['runs', 'export', 'latest']);
assert.equal(exported.status, 0, exported.stderr);
assert.match(exported.stdout, /^## Run task_ok — completed/m);
assert.match(exported.stdout, /^- kind: task$/m);
assert.match(exported.stdout, /^- model: deepseek-flash@latest$/m);
assert.match(exported.stdout, /generated by `moss runs export task_ok`/);
const pausedExport = await cli(['runs', 'export', 'task_paused']);
assert.equal(pausedExport.status, 0, pausedExport.stderr);
assert.match(pausedExport.stdout, /^## Run task_paused — interrupted/m);
assert.ok(!/^- reason: /m.test(pausedExport.stdout));
const failedExport = await cli(['runs', 'export', 'task_fail']);
assert.match(failedExport.stdout, /^- reason: acceptance command failed \(exit 1\)$/m);
assert.match(failedExport.stdout, /^- next: `moss task resume task_fail`$/m);
assert.match(failedExport.stdout, /^- artifacts: taskEvents=\.moss\/task-events\.jsonl$/m);
const stdoutOut = await cli(['runs', 'export', 'latest', '--out=-']);
assert.equal(stdoutOut.status, 0, stdoutOut.stderr);
assert.match(stdoutOut.stdout, /^## Run /);
await assert.rejects(
  () => fs.stat(path.join(ws, '-')),
  '`--out=-` must not create a file named "-"'
);
const exportedJson = await cli(['runs', 'export', 'latest', '--format', 'json']);
assert.equal(JSON.parse(exportedJson.stdout).runId, 'task_ok');
const exportedFile = await cli(['runs', 'export', 'task_fail', '--out', 'out/run.md']);
assert.equal(exportedFile.status, 0, exportedFile.stderr);
const written = await fs.readFile(path.join(ws, 'out', 'run.md'), 'utf8');
assert.match(written, /^## Run task_fail — verify_failed/m);
assert.equal((await cli(['runs', 'export', 'latest', '--format', 'xml'])).status, 2);
assert.equal((await cli(['runs', 'export', 'does-not-exist'])).status, 2);
// B184: --out stays inside the workspace (no ../ or absolute escape).
const escapeOut = await cli(['runs', 'export', 'latest', '--out', '../escape.md']);
assert.equal(escapeOut.status, 2);
assert.match(escapeOut.stderr, /must stay inside the workspace/);
const absoluteOut = await cli(['runs', 'export', 'latest', '--out', path.join(tmp, 'absolute.md')]);
assert.equal(absoluteOut.status, 2);
await assert.rejects(() => fs.stat(path.join(tmp, 'escape.md')));
await assert.rejects(() => fs.stat(path.join(tmp, 'absolute.md')));
ok('single-run export renders Markdown/JSON/--out and rejects bad input');

// 2. Filtered export: one combined PR/CI report.
const [bulk, bulkJsonRun, bulkOut, emptyBulk, badKindRes, conflictRun] = await Promise.all([
  cli(['runs', 'export', '--since', '24h', '--format', 'md']),
  cli(['runs', 'export', '--since', '24h', '--kind', 'task', '--limit', '1', '--json']),
  cli(['runs', 'export', '--since', '24h', '--out', 'runs-report.md']),
  cli(['runs', 'export', '--since', '2100-01-01', '--format', 'md']),
  cli(['runs', 'export', '--kind', 'nope']),
  cli(['runs', 'export', 'task_ok', '--since', '24h']),
]);
assert.equal(bulk.status, 0, bulk.stderr);
assert.match(bulk.stdout, /^# Moss runs — since 24h \(\d+\)/);
assert.match(bulk.stdout, /^## Run /m);
assert.match(bulk.stdout, /^---$/m);
const bulkJson = JSON.parse(bulkJsonRun.stdout);
assert.equal(bulkJson.kind, 'task');
assert.equal(bulkJson.limit, 1);
assert.equal(bulkJson.runs.length, 1);
assert.equal(bulkJson.runs[0].kind, 'task');
assert.ok(bulkJson.ledgerRuns >= bulkJson.total);
assert.equal(bulkOut.status, 0, bulkOut.stderr);
assert.match(await fs.readFile(path.join(ws, 'runs-report.md'), 'utf8'), /^# Moss runs/);
assert.equal(emptyBulk.status, 0);
assert.match(emptyBulk.stdout, /_no runs match_/);
assert.equal(badKindRes.status, 2);
assert.equal(conflictRun.status, 2);
const bulkStdout = await cli(['runs', 'export', '--since', '24h', '--out=-']);
assert.equal(bulkStdout.status, 0, bulkStdout.stderr);
assert.match(bulkStdout.stdout, /^# Moss runs/);
const bulkEscape = await cli(['runs', 'export', '--since', '24h', '--out', '../bulk-escape.md']);
assert.equal(bulkEscape.status, 2);
assert.match(bulkEscape.stderr, /must stay inside the workspace/);
ok('a filtered export renders a combined report (md/json/--out) and validates filters');

await fs.rm(tmp, { recursive: true, force: true });
console.log(`[runs-export] ${checks}/${checks} checks passed`);
