#!/usr/bin/env node
/**
 * `moss init` probe (offline, B135).
 *
 * First-run onboarding must be honest: detect only entry points that exist,
 * propose an acceptance command from real files, write AGENTS.md only when the
 * user has none, and never need a model configuration.
 */
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { captureProcess } from './lib/proc.mjs';

const root = path.resolve(import.meta.dirname, '../..');
let checks = 0;
const ok = (name) => {
  checks += 1;
  console.log(`[init] ok ${name}`);
};

const tmp = await fs.mkdtemp(path.join(os.tmpdir(), 'moss-init-'));
const configDir = path.join(tmp, 'config');
await fs.mkdir(configDir, { recursive: true });

async function fixture(name, files) {
  const dir = path.join(tmp, name);
  await fs.mkdir(path.join(dir, '.git'), { recursive: true });
  await fs.writeFile(path.join(dir, '.git', 'HEAD'), 'ref: refs/heads/main\n', 'utf8');
  for (const [relative, content] of Object.entries(files)) {
    await fs.mkdir(path.dirname(path.join(dir, relative)), { recursive: true });
    await fs.writeFile(path.join(dir, relative), content, 'utf8');
  }
  return dir;
}

const env = {
  ...process.env,
  MOSS_CONFIG_DIR: configDir,
  MOSS_NO_RDK_DOCS: '1',
  MOSS_NO_TUI: '1',
  MOSS_LANG: 'en',
};
const cli = (cwd, args, extraEnv = {}) =>
  captureProcess(process.execPath, [path.join(root, 'dist', 'cli.js'), ...args], {
    cwd,
    env: { ...env, ...extraEnv },
    timeoutMs: 60_000,
  });

try {
  const nodeWs = await fixture('node', {
    'package.json': `${JSON.stringify({
      name: 'demo',
      private: true,
      scripts: { test: 'node --test', build: 'node -e ""', lint: 'eslint .' },
    })}\n`,
  });

  // 1. Node project: detected commands, npm test as the acceptance candidate.
  const json = await cli(nodeWs, ['init', '--json']);
  assert.equal(json.status, 0, json.stderr);
  const result = JSON.parse(json.stdout);
  assert.equal(result.version, 1);
  assert.equal(result.written, true);
  assert.equal(result.exists, false);
  assert.equal(result.detection.kind, 'node');
  assert.deepEqual(
    result.detection.commands.map((entry) => [entry.label, entry.command]),
    [
      ['test', 'npm test'],
      ['build', 'npm run build'],
      ['lint', 'npm run lint'],
    ]
  );
  assert.deepEqual(result.detection.acceptanceCandidates, ['npm test']);
  assert.match(result.content, /## Commands/);
  assert.match(result.content, /- test: `npm test`/);
  assert.match(result.content, /\n```bash\nnpm test\n```\n/);
  assert.match(result.content, /Generated by `moss init`/);
  assert.match(result.content, /Run the test command above before declaring work done/);
  ok('node project: commands + acceptance detected and AGENTS.md written');

  // 2. The file exists now and a second run never overwrites user content.
  const agentPath = path.join(nodeWs, 'AGENTS.md');
  const firstContent = await fs.readFile(agentPath, 'utf8');
  await fs.writeFile(agentPath, `${firstContent}\n- user note: keep me\n`, 'utf8');
  const before = await fs.readFile(agentPath, 'utf8');
  const second = await cli(nodeWs, ['init', '--json']);
  assert.equal(second.status, 0, second.stderr);
  const secondResult = JSON.parse(second.stdout);
  assert.equal(secondResult.exists, true);
  assert.equal(secondResult.written, false);
  assert.equal(await fs.readFile(agentPath, 'utf8'), before);
  ok('an existing AGENTS.md is left byte-identical (no overwrite)');

  // 3. --dry-run on a fresh project writes nothing but shows the content.
  const dryWs = await fixture('dry', {
    Makefile: 'test:\n\tnode -e ""\n',
  });
  const dry = await cli(dryWs, ['init', '--dry-run']);
  assert.equal(dry.status, 0, dry.stderr);
  assert.match(dry.stdout, /--dry-run: nothing written/);
  assert.match(dry.stdout, /- test: `make test`/);
  assert.match(dry.stdout, /moss goal "<intent>" --accept "make test"/);
  await assert.rejects(fs.readFile(path.join(dryWs, 'AGENTS.md')), /ENOENT/);
  ok('--dry-run prints the file and the next command without writing');

  // 4. Python and empty workspaces: honest detection, no invented commands.
  const pyWs = await fixture('python', { 'pyproject.toml': '[project]\nname = "p"\n' });
  const py = await cli(pyWs, ['init', '--json']);
  assert.equal(py.status, 0, py.stderr);
  const pyResult = JSON.parse(py.stdout);
  assert.equal(pyResult.detection.kind, 'python');
  assert.equal(pyResult.detection.acceptanceCandidates.length, 1);
  assert.match(pyResult.detection.acceptanceCandidates[0], /-m pytest/);

  const emptyWs = await fixture('empty', {});
  const empty = await cli(emptyWs, ['init', '--json']);
  assert.equal(empty.status, 0, empty.stderr);
  const emptyResult = JSON.parse(empty.stdout);
  assert.deepEqual(emptyResult.detection.commands, []);
  assert.deepEqual(emptyResult.detection.acceptanceCandidates, []);
  assert.match(emptyResult.content, /No machine-checkable acceptance entry point/);
  ok('python gets pytest; an empty workspace gets no invented command');

  // 4b. B158: CLI init and the interactive `/init` share the detected entry
  // points, and each names the other mode instead of silently diverging.
  {
    const human = await cli(nodeWs, ['init', '--dry-run']);
    assert.equal(human.status, 0, human.stderr);
    assert.match(human.stdout, /\/init\s+# model-drafted variant of this command/);
    const zh = await cli(nodeWs, ['init', '--dry-run'], { MOSS_LANG: 'zh' });
    assert.equal(zh.status, 0, zh.stderr);
    assert.match(zh.stdout, /\/init\s+# 本命令的模型草稿版/);

    const registry = await import(
      pathToFileURL(path.join(root, 'dist/cli/commands/registry.js')).href
    );
    const freshNode = await fixture('agents-fresh-node', {
      'package.json': JSON.stringify({ scripts: { test: 'vitest run', build: 'tsc' } }),
    });
    const detected = registry.buildInitPrompt(freshNode);
    assert.match(detected, /Verified entry points detected from files \(node\)/);
    assert.match(detected, /- test: npm test/);
    assert.match(detected, /keep them verbatim unless running them proves otherwise/);
    assert.match(detected, /Do not invent commands/);

    const existing = await fixture('agents-existing', {
      'package.json': JSON.stringify({ scripts: { test: 'vitest run' } }),
      'AGENTS.md': '# AGENTS.md\n\nKeep this line.\n',
    });
    const review = registry.buildInitPrompt(existing);
    assert.match(review, /update it incrementally/);
    assert.match(review, /Never delete a user instruction/);
    assert.match(review, /- test: npm test/);

    const blank = await fixture('agents-empty', {});
    const draft = registry.buildInitPrompt(blank);
    assert.match(draft, /No build\/test entry point was detected/);
    assert.match(draft, /Say so explicitly rather than inventing commands/);
  }
  ok('CLI init and /init share detection and each names the other mode');

  // 5. Help/usage and bad arguments behave like every other subcommand.
  const help = await cli(nodeWs, ['init', '--help']);
  assert.equal(help.status, 0, help.stderr);
  assert.match(help.stdout, /moss init \[--dry-run\] \[--json\]/);
  const bad = await cli(nodeWs, ['init', '--bogus']);
  assert.equal(bad.status, 2);
  assert.match(bad.stderr, /unknown argument --bogus/);
  const full = await cli(nodeWs, ['--help', '--all']);
  assert.match(full.stdout, /init\s+first-run: detect this project/);
  ok('--help/--bogus/full-help behave; the command is discoverable');
} finally {
  await fs.rm(tmp, { recursive: true, force: true });
}

console.log(`[init] ${checks}/${checks} checks passed`);
