#!/usr/bin/env node
import fs from 'node:fs';
import path from 'node:path';
import process from 'node:process';
import { fileURLToPath } from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const defaultPackageDir = path.resolve(scriptDir, '..');

function argValue(name) {
  const index = process.argv.indexOf(name);
  return index >= 0 ? process.argv[index + 1] : undefined;
}

const packageDir = path.resolve(argValue('--package-dir') || defaultPackageDir);
const keyPath = path.join(packageDir, 'bundled-search-key.json');
const markerPath = path.join(packageDir, '.bundled-search-key.generated');

function readEnvFile(filePath) {
  try {
    const content = fs.readFileSync(filePath, 'utf-8');
    for (const line of content.split('\n')) {
      const trimmed = line.trim();
      if (!trimmed || trimmed.startsWith('#')) continue;
      const eqIdx = trimmed.indexOf('=');
      if (eqIdx === -1) continue;
      const key = trimmed.slice(0, eqIdx).trim();
      const value = trimmed
        .slice(eqIdx + 1)
        .trim()
        .replace(/^["']|["']$/g, '');
      if (key === 'BOCHA_API_KEY' && value) return value;
    }
  } catch {
    // file not found — fall through
  }
  return undefined;
}

function resolveBochaKey() {
  // 1. process.env (set by CI or shell)
  if (process.env.BOCHA_API_KEY) return process.env.BOCHA_API_KEY;

  // 2. .env file in the monorepo root (parent of package dir)
  const monorepoRoot = path.resolve(packageDir, '..', '..');
  return readEnvFile(path.join(monorepoRoot, '.env'));
}

if (fs.existsSync(keyPath)) {
  try {
    const existing = JSON.parse(fs.readFileSync(keyPath, 'utf8'));
    if (existing.bochaApiKey) {
      console.error(`[search-key] using existing ${path.relative(packageDir, keyPath)}`);
      process.exit(0);
    }
  } catch {
    // invalid JSON — fall through to regenerate
  }
}

const bochaKey = resolveBochaKey();
if (!bochaKey) {
  // Not an error — keyless search (Bing/DuckDuckGo) is the fallback.
  // Only warn so that dev builds without a key don't fail.
  console.error('[search-key] no BOCHA_API_KEY found — packaged build will use keyless search');
  process.exit(0);
}

// 0644, NOT 0600: npm preserves tar modes on install, and `sudo npm i -g`
// leaves the file root-owned. With 0600 every non-root user got a silent
// EACCES. This key is a shared gateway key by design, so world-readable is fine.
fs.writeFileSync(keyPath, `${JSON.stringify({ bochaApiKey: bochaKey }, null, 2)}\n`, {
  mode: 0o644,
});
fs.writeFileSync(markerPath, 'generated by prepare-bundled-search-key.mjs\n', { mode: 0o644 });
console.error(`[search-key] generated ${path.relative(packageDir, keyPath)} for package packing`);
